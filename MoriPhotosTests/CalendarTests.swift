        let calendarID = calendar.calendarIdentifier
        defer { if let ownedCalendar = store.calendar(withIdentifier: calendarID) { try? store.removeCalendar(ownedCalendar, commit: true) } }
        let layout = CalendarLayout(), start = layout.defaultStart(on: layout.addingDays(2, to: Date()))
        let event = EKEvent(eventStore: store)
        event.calendar = calendar; event.title = "重复日程集成测试"; event.startDate = start; event.endDate = start.addingTimeInterval(3600)
