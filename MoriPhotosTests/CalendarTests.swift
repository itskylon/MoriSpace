    func testRealEventKitRoundTripRecurrenceSelectedOccurrenceAndDeletion() async throws {
        guard EKEventStore.authorizationStatus(for: .event) == .fullAccess else { throw XCTSkip("Isolated simulator requires Calendar full access") }
        let provider = SystemCalendarProvider(), store = provider.eventStore
        guard let source = store.sources.first(where: { $0.sourceType == .local }) else { throw XCTSkip("No local calendar source in the simulator") }
        let calendar = EKCalendar(for: .event, eventStore: store)
        calendar.title = "MoriCalendarUnitTest-" + UUID().uuidString; calendar.source = source
